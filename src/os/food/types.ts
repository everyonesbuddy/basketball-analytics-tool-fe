export type Slot = "breakfast" | "lunch" | "dinner";
export type Mode = "cook" | "order";
export type Meal = { key: string; name: string; cuisine: string; mins: number; mode: "cook" | "order" | "both"; slots: Slot[]; search: string; batch?: boolean; note?: string; order?: string; link?: string; custom?: boolean; orderUrl: string };
export type Ideas = { date: string; planned: (Meal & { mode: Mode }) | null; leftovers: { key: string; name: string } | null; slots: Record<Slot, Record<Mode, Meal[]>> };
export type PlanDay = { date: string; weekday: string; mode: Mode; key: string; lunch: string | null };
export type GroceryItem = { name: string; aisle: string; for: string[]; staple: boolean; bought: boolean };
export type MealPlan = { _id?: string; weekStart: string; days: PlanDay[]; grocery: GroceryItem[] };
export type FoodSettings = { tortillas: boolean; sugar: "little" | "none"; cuisines: string[]; weeknightMax: number; cookNights: number; likes: string[]; dislikes: string[] };
export type MealLog = { _id: string; date: string; slot: Slot; key: string; name: string; cuisine: string; mode: Mode };
export type CustomMeal = { _id: string; name: string; cuisine: string; slots: Slot[]; mins: number; mode: string; ingredients: string; link: string };
export type FoodOverview = {
  date: string;
  weekday: string;
  thisWeek: string;
  nextWeek: string;
  settings: FoodSettings;
  recent: MealLog[];
  plans: { current: MealPlan | null; next: MealPlan | null };
  custom: CustomMeal[];
  ideas: Ideas;
  meals: Meal[];
  cuisines: string[];
  aisles: { key: string; name: string }[];
};
export const SLOT_NAME: Record<Slot, string> = { breakfast: "Breakfast", lunch: "Lunch", dinner: "Dinner" };
